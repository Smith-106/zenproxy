#!/usr/bin/env node
// Regenerates internal/forward/gateprompts.go from captured official-client
// requests.
//
// Why this exists: the free tier only answers requests whose first system
// message repeats a long verbatim chunk of one of the OpenCode client's own
// system prompts (see internal/forward/freegate.go). Those chunks are data,
// not logic, so they are extracted from a real capture instead of being
// retyped — a single altered character inside the required span costs the
// whole request.
//
// Usage:
//   node scripts/extract-gate-prompts.mjs <title-body.json> <agent-body.json>
//
// Both inputs are request bodies captured from the official client talking to
// a local logging listener (see docs/FREE-TIER.md for the capture recipe).
// Only `model`/`messages` are read; nothing is echoed to stdout.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const CHUNK = 1600;
// The upstream demands at least five of the client's tool names; asking for one
// more leaves room for a client whose own tool happens to collide with one.
const MIN_TOOL_NAMES = 6;

const [titlePath, agentPath] = process.argv.slice(2);
if (!titlePath || !agentPath) {
  console.error("usage: extract-gate-prompts.mjs <title-body.json> <agent-body.json>");
  process.exit(2);
}

const systemPrompt = (file) => {
  const body = JSON.parse(fs.readFileSync(file, "utf8"));
  const msg = (body.messages ?? []).find((m) => m.role === "system" && typeof m.content === "string");
  if (!msg) throw new Error(`no string system message in ${file}`);
  return msg.content;
};

const title = systemPrompt(titlePath);
const agent = systemPrompt(agentPath);
const agentBody = JSON.parse(fs.readFileSync(agentPath, "utf8"));
const toolNames = (agentBody.tools ?? []).map((t) => t.function?.name).filter(Boolean);
if (toolNames.length === 0) throw new Error("the agent capture advertises no tools");
for (const [name, text, marker] of [
  ["title", title, "You are a title generator"],
  ["agent", agent, "You are opencode, an interactive CLI tool"],
]) {
  if (!text.startsWith(marker)) {
    throw new Error(`${name} prompt does not start with the expected marker ${JSON.stringify(marker)}`);
  }
  if (text.length < CHUNK) throw new Error(`${name} prompt is shorter than ${CHUNK} characters`);
}

const out = `// Code generated by scripts/extract-gate-prompts.mjs from a captured official
// client request. DO NOT EDIT by hand: the free-tier matcher compares verbatim
// text, so a retyped character breaks every request.
//
// These are the first ${CHUNK} characters of the two system prompts the OpenCode
// client sends. The upstream requires one of them, chosen by the shape of the
// request: the title prompt only passes with no \`tools\`, the agent prompt only
// passes with \`tools\` present.
package forward

// gateTitleChunk is the head of the client's title-generation prompt.
const gateTitleChunk = ${JSON.stringify(title.slice(0, CHUNK))}

// gateBuildChunk is the head of the client's coding-agent prompt.
const gateBuildChunk = ${JSON.stringify(agent.slice(0, CHUNK))}

// gateToolNames are the names of the tools the client always advertises. A
// request that carries \`tools\` must include at least ${MIN_TOOL_NAMES} of them —
// names only, the schemas and the order are not looked at. gateMinToolNames is
// the threshold this proxy aims for, one above the observed boundary so that a
// client tool of its own cannot push the count back under it.
var gateToolNames = []string{${toolNames.map((n) => JSON.stringify(n)).join(", ")}}

// gateMinToolNames is how many of gateToolNames a request must carry.
const gateMinToolNames = ${MIN_TOOL_NAMES}
`;

const dest = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "internal", "forward", "gateprompts.go");
fs.writeFileSync(dest, out);
console.log(`wrote ${dest} (${out.length} bytes, title ${title.length} chars, agent ${agent.length} chars)`);
